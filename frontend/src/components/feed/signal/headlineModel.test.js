import { describe, expect, it } from "vitest";
import { headlineParts, emphasisedNumbers } from "./headlineModel";

describe("headlineParts", () => {
  it.each([
    ['דריימונד גרין החמיא לאבדיה: "עם דני תמיד יש סיכוי לנצח"', "דריימונד גרין החמיא לאבדיה", "עם דני תמיד יש סיכוי לנצח"],
    ['התחזית ששמה את דני אבדיה באולסטאר ה-NBA: "הסיר את כל הספקות"', "התחזית ששמה את דני אבדיה באולסטאר ה-NBA", "הסיר את כל הספקות"],
    ['יחס משפיל? מכבי תל אביב הגיבה: "פעלנו על פי הנחיות המשטרה"', "יחס משפיל? מכבי תל אביב הגיבה", "פעלנו על פי הנחיות המשטרה"],
    ['בנבחרת זועמים: "אם ליף היה מודיע מראש, לא היינו משחררים את סורקין"', "בנבחרת זועמים", "אם ליף היה מודיע מראש, לא היינו משחררים את סורקין"],
    ['"באנו במיוחד מהארץ": גאווה ושברון לב עם אבדיה בגארדן', "גאווה ושברון לב עם אבדיה בגארדן", "באנו במיוחד מהארץ"],
    ['"מתנצל בפני מי שנפגע. זו הייתה דאחקה"', null, "מתנצל בפני מי שנפגע. זו הייתה דאחקה"],
    ['מאמן: “ניצחנו את ת"א”', "מאמן", 'ניצחנו את ת"א'],
    ['״באנו לנצח״: המאמן מסביר', "המאמן מסביר", "באנו לנצח"],
    ['“יש סיכוי”', null, "יש סיכוי"],
    ['מאמן: " יש סיכוי "  ', "מאמן", " יש סיכוי "],
  ])("splits anchored quotes in %s", (title, context, quote) => {
    expect(headlineParts(title)).toEqual({ kind: "quote", context, quote });
  });

  it.each([
    'במכבי ת"א תוהים: מה קרה למאמן שהוציא מים מהסלע?',
    'מכבי ת"א הודיעה: הרשתות ביציע הוסרו בהיכל',
    "אקס מכבי תל אביב הורחק - והבינה המלאכותית חטפה את האש",
    'ניצחון גדול לארה"ב',
    'מאמן: ת"א וארה"ב',
    'ת"א:ב"ש',
    'ה"קוסם" חזר לשחק',
    'מאמן: "היה טוב" והמשיך לדבר',
    '"הקוסם" חזר לשחק',
    'מאמן: ""',
    "",
  ])("keeps acronyms, nicknames and partial quotes plain: %s", (title) => {
    expect(headlineParts(title)).toEqual({ kind: "plain" });
  });
});

describe("emphasisedNumbers", () => {
  it.each([
    ["על ההתבטאויות נגד השופטים: עופר ינאי נקנס ב-60 אלף שקל", ["60 אלף שקל"]],
    ["יוקיץ' התקרב לשיא ההיסטורי ב-145:151 של דנבר", ["145:151"]],
    ["מהפך אדיר: אטלנטה ניצחה את דטרויט אחרי ריצת 0:18", ["0:18"]],
    ["ערב ענק: אבדיה כיכב עם 31 נקודות", ["31 נקודות"]],
    ["הצהובים מגיעים מהמקום ה-19 ב-2026", []],
    ["2 מיליון דולר, 3 אלף יורו, 4 שקל, 5 דולר, 6 יורו", ["2 מיליון דולר", "3 אלף יורו", "4 שקל", "5 דולר", "6 יורו"]],
    ["7 ריבאונדים ו-8 אסיסטים, 9 שערים ב-10 דקות", ["7 ריבאונדים", "8 אסיסטים", "9 שערים", "10 דקות"]],
    ["11 אלף ו-12 מיליון", ["11 אלף", "12 מיליון"]],
    ["31 נקודותיים 60 אלפים 2026 12:30:45", []],
    ["", []],
  ])("highlights only scores and supported units in %s, losslessly", (title, expected) => {
    const segments = emphasisedNumbers(title);
    expect(segments.filter((part) => part.emphasis).map((part) => part.text)).toEqual(expected);
    expect(segments.map((part) => part.text).join("")).toBe(title);
  });
});
